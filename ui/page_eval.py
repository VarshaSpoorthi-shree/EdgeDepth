def _bench_df(rows):
    df = pd.DataFrame(rows)
    df["Method"] = df["method"].map(METHOD_LABELS)
    return df


def live_section():
    st.markdown("### Live evaluation of your last comparison run")
    data = st.session_state.get("cmp_results")
    if not data:
        st.info("Run **Method Comparison** first — its metrics appear here.")
        return
    b, res = data["bundle"], data["res"]
    df = metrics_frame(res, b.gt is not None)
    st.dataframe(df.style.format(precision=4), width="stretch", hide_index=True)
    if b.gt is None:
        st.warning("No ground truth → RMSE / MAE / PSNR / SSIM / edge metrics are not available for this input. Only latency and memory are reported.")
    ok = {m: r for m, r in res.items() if r["depth"] is not None}
    keys = (["rmse", "b_rmse", "edge_f1", "ssim"] if b.gt is not None else []) + ["latency_ms", "memory_mb"]
    cols = st.columns(2)
    for i, k in enumerate(keys):
        vals = [(r["metrics"][k] if k in METRIC_KEYS else r[k]) for r in ok.values()]
        fig = go.Figure(go.Bar(x=[METHOD_LABELS[m] for m in ok], y=vals,
                               marker_color=["#4FD1C5" if m == "hybrid" else "#5B6B82" for m in ok]))
        fig.update_layout(title=METRIC_LABELS[k], height=300, **LAYOUT)
        cols[i % 2].plotly_chart(fig, width="stretch")


def mini_benchmark():
    st.markdown("### Run a live mini-benchmark on unseen test frames")
    test_dir = os.path.join(ROOT, "data", "nyu", "test")
    if not os.path.isdir(test_dir):
        st.info("Test split not present (data/nyu/test).")
        return
    c = st.columns(4)
    n = c[0].slider("Frames", 1, 8, 3)
    s = c[1].select_slider("Factor", [2, 4, 8], value=4)
    noisy = c[2].toggle("Noise + missing", value=True)
    go_ = c[3].button("Run benchmark", width="stretch")
    if not go_:
        return
    from edgedepth.model.dataset import load_split

    frames = load_split(os.path.join(ROOT, "data", "nyu"), "test")[: n * 3: 3]
    methods = method_options(model_available())
    rows = []
    prog = st.progress(0.0, text="evaluating …")
    for i, (name, rgb, gt) in enumerate(frames):
        cfg = DegradationConfig(scale=s, seed=20000 + i * 3, **(dict(noise_level=1.0, missing_rate=0.05, edge_dropout=0.5) if noisy else {}))
        res = run_methods(rgb, degrade(gt, cfg), methods, gt=gt, track_memory=False)
        for m, r in res.items():
            if r["metrics"]:
                rows.append({"frame": name, "Method": METHOD_LABELS[m], **r["metrics"], "latency_ms": r["latency_ms"]})
        prog.progress((i + 1) / len(frames), text=f"{i + 1}/{len(frames)} frames")
    df = pd.DataFrame(rows).groupby("Method", sort=False).mean(numeric_only=True).reset_index()
    st.dataframe(df.rename(columns=METRIC_LABELS).style.format(precision=4), width="stretch", hide_index=True)


def benchmark_section():
    s = load_json("summary.json")
    st.markdown("### Benchmark on the unseen NYU Depth V2 test split")
    if not s:
        st.info("results/summary.json not found — run `python scripts/evaluate.py`.")
        return
    p = s["protocol"]
    st.caption(f"{len(p['test_frames'])} test frames · {p['resolution'][1]}×{p['resolution'][0]} · conditions: clean, noisy+missing "
               f"(Kinect noise ×1, 5% dropout, 50% edge dropout), sparse 5% · {p['machine']} · generated by scripts/evaluate.py")
    df = _bench_df(s["by_scale_condition"])
    conds = list(dict.fromkeys(df["condition"]))
    c1, c2 = st.columns(2)
    cond = c1.selectbox("Condition", conds, index=conds.index("noisy_missing") if "noisy_missing" in conds else 0)
    metric = c2.selectbox("Metric", METRIC_KEYS + ["latency_ms"], format_func=lambda k: METRIC_LABELS[k])
    sub = df[df["condition"] == cond]
    if cond != "sparse_5pct":
        fig = px.line(sub, x="scale", y=metric, color="Method", markers=True, title=f"{METRIC_LABELS[metric]} vs upsampling factor")
        fig.update_layout(height=380, **LAYOUT)
        st.plotly_chart(fig, width="stretch")
    piv = sub.pivot_table(index="Method", columns="scale", values=metric, sort=False)
    st.dataframe(piv.style.format(precision=4), width="stretch")

    st.markdown("#### Full table (selected condition)")
    show = sub[["scale", "Method"] + METRIC_KEYS + ["latency_ms"]].rename(columns=METRIC_LABELS)
    st.dataframe(show.style.format(precision=4), width="stretch", hide_index=True)

    if s.get("memory_mb_4x"):
        st.markdown("#### Peak memory at 4× (320×240 output)")
        mem = s["memory_mb_4x"]
        fig = go.Figure(go.Bar(x=[METHOD_LABELS[m] for m in mem], y=list(mem.values()), marker_color="#5B6B82"))
        fig.update_layout(height=280, yaxis_title="MB (approx.)", **LAYOUT)
        st.plotly_chart(fig, width="stretch")

    if s.get("cross_dataset"):
        st.markdown("#### Cross-dataset generalisation (TUM RGB-D, SUN RGB-D, Redwood — never seen in training)")
        st.caption("Reference = the raw sensor depth (holes excluded); low-res input = masked box-downsampling of it.")
        cd = _bench_df(s["cross_dataset"])
        st.dataframe(cd[["scale", "Method"] + METRIC_KEYS].rename(columns=METRIC_LABELS).style.format(precision=4), width="stretch", hide_index=True)

    a = load_json("ablation.json")
    if a:
        st.markdown("#### Ablation study (test split, mean over 2×/4×/8× × clean/noisy)")
        ad = pd.DataFrame([r for r in a["rows"] if r["scale"] == "all"])
        st.dataframe(ad[["variant"] + METRIC_KEYS + ["latency_ms"]].rename(columns=METRIC_LABELS).style.format(precision=4), width="stretch", hide_index=True)

    t = load_json("training_log.json")
    if t and t.get("history"):
        st.markdown("#### Training curve (EdgeDepthNet)")
        h = pd.DataFrame(t["history"])
        v = pd.DataFrame(t["val"])
        fig = go.Figure()
        fig.add_trace(go.Scatter(x=h["iter"], y=h["l1_ref"], name="train L1 (m, crops)"))
        fig.add_trace(go.Scatter(x=v["iter"], y=v["mean"], name="val RMSE (m, full frames)", mode="lines+markers"))
        fig.update_layout(height=320, xaxis_title="iteration", **LAYOUT)
        st.plotly_chart(fig, width="stretch")


